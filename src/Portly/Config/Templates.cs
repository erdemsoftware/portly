using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Portly.Core;

namespace Portly.Config
{
    /// <summary>
    /// Config templates use {{NAME}} placeholders.
    /// A copy in usr\templates\ overrides the shipped one in templates\ (and survives updates).
    /// </summary>
    public static class Templates
    {
        public static string PathOf(string name)
        {
            var user = Path.Combine(Paths.UserTemplates, name);
            return File.Exists(user) ? user : Path.Combine(Paths.Templates, name);
        }

        public static string Render(string name, IDictionary<string, string> vars)
        {
            var text = File.ReadAllText(PathOf(name), Encoding.UTF8);
            foreach (var kv in vars) text = text.Replace("{{" + kv.Key + "}}", kv.Value ?? "");
            return text;
        }

        /// <summary>Write only when the content changed (keeps timestamps stable).</summary>
        public static bool WriteIfChanged(string path, string content)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            if (File.Exists(path) && File.ReadAllText(path, Encoding.UTF8) == content) return false;
            File.WriteAllText(path, content, new UTF8Encoding(false));
            return true;
        }

        public static Dictionary<string, string> CommonVars()
        {
            var s = Settings.Current;
            return new Dictionary<string, string>
            {
                { "ROOT", Paths.Fwd(Paths.Root) },
                { "ETC", Paths.Fwd(Paths.Etc) },
                { "LOGS", Paths.Fwd(Paths.Logs) },
                { "TMP", Paths.Fwd(Paths.Tmp) },
                { "DATA", Paths.Fwd(Paths.Data) },
                { "DOC_ROOT", Paths.Fwd(s.DocumentRoot) },
                { "HTTP_PORT", s.HttpPort.ToString() },
                { "HTTPS_PORT", s.HttpsPort.ToString() },
                { "BIND", s.AllowLan ? "0.0.0.0" : "127.0.0.1" },
                { "GENERATED", "Generated by Portly " + AppInfo.VersionText + " - changes are overwritten. Copy the template to usr\\templates to customize." },
            };
        }
    }
}
