using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Portly.Core;
using Portly.Packages;

namespace Portly.Config
{
    /// <summary>The http://localhost dashboard and the web tools (Adminer, phpMyAdmin).</summary>
    public static class ToolApps
    {
        public static string DashboardDir { get { return Path.Combine(Paths.Apps, "dashboard"); } }

        /// <summary>(url name, folder) of installed web tools.</summary>
        public static List<Tuple<string, string>> WebTools()
        {
            var list = new List<Tuple<string, string>>();
            foreach (var t in new[] { "adminer", "phpmyadmin" })
            {
                var dir = PackageTypes.ActiveDir(t);
                if (dir != null) list.Add(Tuple.Create(t, dir));
            }
            var pma = PackageTypes.ActiveDir("phpmyadmin");
            if (pma != null) ConfigurePhpMyAdmin(pma);
            return list;
        }

        public static void WriteDashboard(List<Site> sites, bool ssl)
        {
            Directory.CreateDirectory(DashboardDir);
            var src = Path.Combine(Paths.Templates, "dashboard", "index.php");
            if (File.Exists(src)) Templates.WriteIfChanged(Path.Combine(DashboardDir, "index.php"), File.ReadAllText(src, Encoding.UTF8));

            var s = Settings.Current;
            var tools = new List<object>();
            foreach (var t in WebTools()) tools.Add(new Dictionary<string, object> { { "name", PackageTypes.Get(t.Item1).Name }, { "url", "/" + t.Item1 + "/" } });
            if (PackageTypes.ActiveDir(s.MailTool) != null)
                tools.Add(new Dictionary<string, object> { { "name", PackageTypes.Get(s.MailTool).Name }, { "url", "http://127.0.0.1:" + s.MailpitWebPort + "/" } });

            var data = new Dictionary<string, object>
            {
                { "version", AppInfo.VersionText },
                { "edition", AppInfo.EditionName },
                { "docRoot", s.DocumentRoot },
                { "github", AppInfo.GitHubUrl },
                { "donate", AppInfo.DonateUrl },
                { "sites", sites.Select(x => (object)new Dictionary<string, object>
                    {
                        { "name", x.Name },
                        { "url", x.Valid ? x.Url(ssl) : "" },
                        { "php", PackageTypes.Label(x.PhpFolder) },
                        { "problem", x.Problem },
                        { "aliases", x.Aliases.ToList() },
                    }).ToList() },
                { "tools", tools },
                { "t", new Dictionary<string, object>
                    {
                        { "title", I18n.T("dash.title") }, { "sites", I18n.T("dash.sites") }, { "tools", I18n.T("dash.tools") },
                        { "empty", I18n.T("dash.empty", s.DocumentRoot) }, { "phpinfo", I18n.T("dash.phpinfo") },
                        { "donate", I18n.T("dash.donate") }, { "lang", I18n.Code },
                    } },
            };
            Templates.WriteIfChanged(Path.Combine(DashboardDir, "data.json"), Json.Serialize(data));
        }

        /// <summary>phpMyAdmin config: cookie login, empty root password allowed (local only), current MySQL port.</summary>
        public static void ConfigurePhpMyAdmin(string dir)
        {
            try
            {
                var ini = Settings.Current.Raw;
                var secret = ini.Get("phpmyadmin", "Secret", "");
                if (secret.Length != 32)
                {
                    var b = new byte[24];
                    using (var r = RandomNumberGenerator.Create()) r.GetBytes(b);
                    secret = Convert.ToBase64String(b).Replace('+', 'a').Replace('/', 'b').Substring(0, 32);
                    ini.Set("phpmyadmin", "Secret", secret);
                    Settings.Current.Save();
                }
                var tmp = Path.Combine(Paths.Tmp, "phpmyadmin");
                Directory.CreateDirectory(tmp);
                var php = "<?php\n// Generated by Portly\n" +
                          "$cfg['blowfish_secret'] = '" + secret + "';\n" +
                          "$i = 1;\n" +
                          "$cfg['Servers'][$i]['auth_type'] = 'cookie';\n" +
                          "$cfg['Servers'][$i]['host'] = '127.0.0.1';\n" +
                          "$cfg['Servers'][$i]['port'] = '" + Settings.Current.MysqlPort + "';\n" +
                          "$cfg['Servers'][$i]['AllowNoPassword'] = true;\n" +
                          "$cfg['TempDir'] = '" + Paths.Fwd(tmp) + "';\n" +
                          "$cfg['VersionCheck'] = false;\n";
                Templates.WriteIfChanged(Path.Combine(dir, "config.inc.php"), php);
            }
            catch (Exception ex) { Log.Warn("phpMyAdmin config: " + ex.Message); }
        }
    }
}
